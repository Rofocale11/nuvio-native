//! Strict parser for the static SegmentBase MPD the shim synthesises for trailer DASH.
//!
//! The bundled FFmpeg has no `dash` demuxer (only `mov`), so `.mpd` cannot go through the
//! progressive path. This parser accepts exactly the shape
//! `pmsshim::dash_manifest` generates — two AdaptationSets (one video, one audio), each with
//! a `SegmentBase` (init + index ranges) and a single Representation whose `BaseURL` is an
//! https googlevideo URL or a `http://127.0.0.1` trailer-proxy URL — and rejects everything that would change how bytes must be
//! assembled (SegmentTemplate/List, timelines, encryption/cenc, unknown mime, no-https
//! BaseURL outside loopback). No xml crate: the input is generated by us and is small; a hand-rolled tag
//! scanner is enough and keeps the invalid-input surface explicit.
//!
//! Each Representation is one fMP4 file (init + segments contiguous), so the demuxer treats
//! each track's BaseURL as a seekable progressive source via the `mov` demuxer.

use std::fmt;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DashTrack {
    /// BaseURL, XML-unescaped. Always https, or a `http://127.0.0.1` trailer-proxy
    /// URL (rejected otherwise).
    pub base_url: String,
    /// AdaptationSet mimeType, e.g. `video/mp4` / `audio/mp4`.
    pub mime: String,
    pub width: i64,
    pub height: i64,
    /// `codecs` attribute if the manifest carries one, else the mime string.
    pub codec: String,
    /// Initialization byte range (`start-end`, inclusive) from `SegmentBase/Initialization`.
    pub init_range: (i64, i64),
    /// `indexRange` from `SegmentBase`.
    pub index_range: (i64, i64),
    pub bandwidth: i64,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DashManifest {
    pub video: DashTrack,
    pub audio: DashTrack,
    pub duration_ms: Option<i64>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Error {
    NotMpd,
    DynamicManifest,
    Unsupported(&'static str),
    UnknownMime(String),
    MissingRepresentation,
    /// A track parsed but its sibling kind never appeared.
    MissingTrack(&'static str),
    NonHttpsBaseUrl,
    MissingBaseUrl,
    MissingRange(&'static str),
    BadRange(String),
    BadDuration(String),
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Error::NotMpd => write!(f, "no MPD root"),
            Error::DynamicManifest => write!(f, "dynamic (non-static) MPD rejected"),
            Error::Unsupported(what) => write!(f, "unsupported DASH feature: {what}"),
            Error::UnknownMime(mime) => write!(f, "unknown mimeType: {mime}"),
            Error::MissingRepresentation => write!(f, "Representation without BaseURL"),
            Error::MissingTrack(kind) => write!(f, "missing {kind} AdaptationSet"),
            Error::NonHttpsBaseUrl => write!(f, "BaseURL is not https"),
            Error::MissingBaseUrl => write!(f, "missing BaseURL"),
            Error::MissingRange(what) => write!(f, "missing {what} range"),
            Error::BadRange(s) => write!(f, "bad byte range: {s}"),
            Error::BadDuration(s) => write!(f, "bad mediaPresentationDuration: {s}"),
        }
    }
}

impl std::error::Error for Error {}

fn xml_unescape(s: &str) -> String {
    if !s.contains('&') {
        return s.to_string();
    }
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(pos) = rest.find('&') {
        out.push_str(&rest[..pos]);
        let tail = &rest[pos + 1..];
        let semi = match tail.find(';') {
            Some(i) => i,
            None => {
                out.push('&');
                rest = tail;
                continue;
            }
        };
        let entity = &tail[..semi];
        let decoded = match entity {
            "amp" => Some("&".to_string()),
            "lt" => Some("<".to_string()),
            "gt" => Some(">".to_string()),
            "quot" => Some("\"".to_string()),
            "apos" => Some("'".to_string()),
            _ if entity.starts_with("#x") || entity.starts_with("#X") => {
                u32::from_str_radix(&entity[2..], 16)
                    .ok()
                    .and_then(char::from_u32)
                    .map(|c| c.to_string())
            }
            _ if entity.starts_with('#') => entity[1..]
                .parse::<u32>()
                .ok()
                .and_then(char::from_u32)
                .map(|c| c.to_string()),
            _ => None,
        };
        match decoded {
            Some(d) => out.push_str(&d),
            None => {
                out.push('&');
                out.push_str(entity);
                out.push(';');
            }
        }
        rest = &tail[semi + 1..];
    }
    out.push_str(rest);
    out
}

/// A track's `BaseURL` may be an `https://` CDN URL (the direct path) or a
/// `http://127.0.0.1` / `http://localhost` trailer-proxy URL (the Node child with
/// the IOS user agent). Plain HTTP to any other host is refused: loopback only.
fn base_url_allowed(text: &str) -> bool {
    if text.starts_with("https://") {
        return true;
    }
    let Some(rest) = text.strip_prefix("http://") else {
        return false;
    };
    let authority = rest.split('/').next().unwrap_or_default();
    let host = match authority.rfind('@') {
        Some(at) => &authority[at + 1..],
        None => authority,
    };
    let host = host
        .strip_prefix('[')
        .map(|h| h.split(']').next().unwrap_or_default())
        .unwrap_or_else(|| host.split(':').next().unwrap_or_default());
    matches!(
        host.to_ascii_lowercase().as_str(),
        "127.0.0.1" | "localhost" | "::1"
    )
}

/// Attribute value from a tag body (`name="value"` or `name='value'`), XML-unescaped.
fn attr(tag_body: &str, name: &str) -> Option<String> {
    let mut rest = tag_body;
    while let Some(pos) = rest.find(name) {
        let after = &rest[pos + name.len()..];
        // Must be a whole attribute name, not the tail of a longer one.
        let before_ok = pos == 0
            || rest.as_bytes()[pos - 1].is_ascii_whitespace()
            || rest.as_bytes()[pos - 1] == b'<';
        let after_trim = after.trim_start();
        if before_ok && after_trim.starts_with('=') {
            let val = after_trim[1..].trim_start();
            if let Some(stripped) = val.strip_prefix('"').or_else(|| val.strip_prefix('\'')) {
                let quote = val.as_bytes()[0] as char;
                if let Some(end) = stripped.find(quote) {
                    return Some(xml_unescape(&stripped[..end]));
                }
            }
        }
        rest = &rest[pos + name.len()..];
    }
    None
}

fn parse_range(s: &str) -> Result<(i64, i64), Error> {
    let (a, b) = s
        .split_once('-')
        .ok_or_else(|| Error::BadRange(s.to_string()))?;
    let start: i64 = a
        .trim()
        .parse()
        .map_err(|_| Error::BadRange(s.to_string()))?;
    let end: i64 = b
        .trim()
        .parse()
        .map_err(|_| Error::BadRange(s.to_string()))?;
    if start < 0 || end < start {
        return Err(Error::BadRange(s.to_string()));
    }
    Ok((start, end))
}

/// ISO-8601 duration `PT#H#M#S` (any subset, fractional seconds) -> milliseconds.
fn parse_duration(s: &str) -> Result<i64, Error> {
    let bad = || Error::BadDuration(s.to_string());
    let rest = s.strip_prefix("PT").ok_or_else(bad)?;
    let (mut ms, mut seen) = (0i64, false);
    let mut cur = String::new();
    let flush =
        |cur: &mut String, unit: char, ms: &mut i64, seen: &mut bool| -> Result<(), Error> {
            if cur.is_empty() {
                return Err(bad());
            }
            let v: f64 = cur.parse().map_err(|_| bad())?;
            if v < 0.0 {
                return Err(bad());
            }
            let add = match unit {
                'H' => (v * 3_600_000.0) as i64,
                'M' => (v * 60_000.0) as i64,
                'S' => (v * 1_000.0) as i64,
                _ => return Err(bad()),
            };
            *ms = ms.saturating_add(add);
            *seen = true;
            cur.clear();
            Ok(())
        };
    for c in rest.chars() {
        match c {
            'H' | 'M' | 'S' => flush(&mut cur, c, &mut ms, &mut seen)?,
            '0'..='9' | '.' => cur.push(c),
            _ => return Err(bad()),
        }
    }
    if !seen || !cur.is_empty() {
        return Err(bad());
    }
    Ok(ms)
}

#[derive(Default)]
struct Adaptation {
    mime: String,
    width: i64,
    height: i64,
    codecs: String,
    index_range: Option<(i64, i64)>,
    init_range: Option<(i64, i64)>,
}

pub fn parse_manifest(xml: &str) -> Result<DashManifest, Error> {
    // Reject features that change byte assembly before any other parsing, so a manifest
    // that smuggles one in anywhere (even after the tracks we accept) fails closed.
    for forbidden in [
        "<SegmentTemplate",
        "<SegmentList",
        "<SegmentTimeline",
        "<SegmentDuration",
        "<ContentProtection",
        "<ContentComponent",
    ] {
        if xml.contains(forbidden) {
            return Err(Error::Unsupported(forbidden.trim_start_matches('<')));
        }
    }
    if xml.contains("cenc") || xml.contains("CENC") {
        return Err(Error::Unsupported("encryption/cenc"));
    }

    let bytes = xml.as_bytes();
    let mut pos = 0usize;
    let mut saw_mpd = false;
    let mut duration_ms: Option<i64> = None;
    let mut adaptation = Adaptation::default();
    let mut in_representation = false;
    let mut pending: Option<DashTrack> = None;
    let mut video: Option<DashTrack> = None;
    let mut audio: Option<DashTrack> = None;

    while pos < bytes.len() {
        let Some(lt) = xml[pos..].find('<') else {
            break;
        };
        let tag_start = pos + lt;
        let Some(gt_rel) = xml[tag_start..].find('>') else {
            return Err(Error::NotMpd);
        };
        let tag_end = tag_start + gt_rel; // index of '>'
        let body = &xml[tag_start + 1..tag_end];
        let trimmed = body.trim_start();
        pos = tag_end + 1;

        // Comments, prolog, doctype, closing tags.
        if trimmed.starts_with('?') || trimmed.starts_with('!') {
            continue;
        }
        if let Some(name) = trimmed.strip_prefix('/') {
            let name = name.trim();
            match name {
                "AdaptationSet" => adaptation = Adaptation::default(),
                "Representation" => {
                    if in_representation {
                        let track = pending.take().ok_or(Error::MissingBaseUrl)?;
                        if track.base_url.is_empty() {
                            return Err(Error::MissingBaseUrl);
                        }
                        if track.mime.starts_with("video/") {
                            video = Some(track);
                        } else if track.mime.starts_with("audio/") {
                            audio = Some(track);
                        }
                    }
                    in_representation = false;
                }
                _ => {}
            }
            continue;
        }
        // Opening / self-closing tag: name is up to whitespace or '/'.
        let name_end = trimmed
            .find(|c: char| c.is_ascii_whitespace() || c == '/')
            .unwrap_or(trimmed.len());
        let name = &trimmed[..name_end];
        let self_closing = trimmed.ends_with('/');

        match name {
            "MPD" => {
                saw_mpd = true;
                if let Some(t) = attr(trimmed, "type") {
                    if t != "static" {
                        return Err(Error::DynamicManifest);
                    }
                }
                if let Some(d) = attr(trimmed, "mediaPresentationDuration") {
                    duration_ms = Some(parse_duration(&d)?);
                }
            }
            "AdaptationSet" => {
                adaptation = Adaptation::default();
                adaptation.mime = attr(trimmed, "mimeType").unwrap_or_default();
                adaptation.width = attr(trimmed, "width")
                    .and_then(|v| v.parse().ok())
                    .unwrap_or(0);
                adaptation.height = attr(trimmed, "height")
                    .and_then(|v| v.parse().ok())
                    .unwrap_or(0);
                adaptation.codecs = attr(trimmed, "codecs").unwrap_or_default();
                if !adaptation.mime.starts_with("video/") && !adaptation.mime.starts_with("audio/")
                {
                    return Err(Error::UnknownMime(adaptation.mime.clone()));
                }
            }
            "SegmentBase" => {
                if let Some(ix) = attr(trimmed, "indexRange") {
                    adaptation.index_range = Some(parse_range(&ix)?);
                }
            }
            "Initialization" => {
                if let Some(r) = attr(trimmed, "range") {
                    adaptation.init_range = Some(parse_range(&r)?);
                }
            }
            "Representation" => {
                in_representation = true;
                let index_range = adaptation
                    .index_range
                    .ok_or(Error::MissingRange("SegmentBase/indexRange"))?;
                let init_range = adaptation
                    .init_range
                    .ok_or(Error::MissingRange("Initialization"))?;
                let codecs = attr(trimmed, "codecs").unwrap_or_else(|| adaptation.codecs.clone());
                let mime = adaptation.mime.clone();
                pending = Some(DashTrack {
                    base_url: String::new(),
                    codec: if codecs.is_empty() {
                        mime.clone()
                    } else {
                        codecs
                    },
                    mime,
                    width: attr(trimmed, "width")
                        .and_then(|v| v.parse().ok())
                        .unwrap_or(adaptation.width),
                    height: attr(trimmed, "height")
                        .and_then(|v| v.parse().ok())
                        .unwrap_or(adaptation.height),
                    init_range,
                    index_range,
                    bandwidth: attr(trimmed, "bandwidth")
                        .and_then(|v| v.parse().ok())
                        .unwrap_or(0),
                });
                if self_closing {
                    // No BaseURL child possible.
                    return Err(Error::MissingBaseUrl);
                }
            }
            "BaseURL" => {
                // Text runs to the closing tag.
                let close = xml[pos..].find("</BaseURL>").ok_or(Error::MissingBaseUrl)?;
                let text = xml_unescape(xml[pos..pos + close].trim());
                if !base_url_allowed(&text) {
                    return Err(Error::NonHttpsBaseUrl);
                }
                if let Some(p) = pending.as_mut() {
                    p.base_url = text;
                } else {
                    return Err(Error::MissingRepresentation);
                }
                pos = pos + close + "</BaseURL>".len();
            }
            _ => {}
        }
    }

    if !saw_mpd {
        return Err(Error::NotMpd);
    }
    let video = video.ok_or(Error::MissingTrack("video"))?;
    let audio = audio.ok_or(Error::MissingTrack("audio"))?;
    Ok(DashManifest {
        video,
        audio,
        duration_ms,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    const SHIM_MANIFEST: &str = r#"<?xml version="1.0" encoding="UTF-8"?>
<MPD xmlns="urn:mpeg:dash:schema:mpd:2011" type="static" mediaPresentationDuration="PT145S" minBufferTime="PT1.5S">
<Period>
<AdaptationSet mimeType="video/mp4" width="1920" height="1080" frameRate="24" segmentAlignment="true">
<SegmentBase timescale="1000" indexRange="1000-2000"><Initialization range="0-999"/></SegmentBase>
<Representation id="137" bandwidth="5000000">
<BaseURL>https://rr1.googlevideo.com/videoplayback?expire=1&amp;id=137&amp;sig=a%3Db</BaseURL>
</Representation>
</AdaptationSet>
<AdaptationSet mimeType="audio/mp4" segmentAlignment="true">
<SegmentBase timescale="1000" indexRange="3000-4000"><Initialization range="2001-2999"/></SegmentBase>
<Representation id="140" bandwidth="128000">
<BaseURL>https://rr1.googlevideo.com/videoplayback?expire=1&amp;id=140&amp;sig=c%3Dd</BaseURL>
</Representation>
</AdaptationSet>
</Period>
</MPD>
"#;

    #[test]
    fn parses_shim_shaped_manifest_with_two_tracks() {
        let m = parse_manifest(SHIM_MANIFEST).expect("shim manifest parses");
        assert_eq!(m.video.mime, "video/mp4");
        assert_eq!((m.video.width, m.video.height), (1920, 1080));
        assert_eq!(m.video.init_range, (0, 999));
        assert_eq!(m.video.index_range, (1000, 2000));
        assert_eq!(m.video.bandwidth, 5_000_000);
        assert_eq!(m.audio.mime, "audio/mp4");
        assert_eq!(m.audio.init_range, (2001, 2999));
        assert_eq!(m.audio.index_range, (3000, 4000));
        assert_eq!(m.duration_ms, Some(145_000));
    }

    #[test]
    fn unescapes_base_url_entities() {
        let m = parse_manifest(SHIM_MANIFEST).expect("parses");
        assert_eq!(
            m.video.base_url,
            "https://rr1.googlevideo.com/videoplayback?expire=1&id=137&sig=a%3Db"
        );
        assert_eq!(
            m.audio.base_url,
            "https://rr1.googlevideo.com/videoplayback?expire=1&id=140&sig=c%3Dd"
        );
    }

    #[test]
    fn rejects_segment_template() {
        let bad = SHIM_MANIFEST.replacen(
            "<SegmentBase",
            "<SegmentTemplate timescale=\"1000\" media=\"seg$Number$.m4s\"/><SegmentBase",
            1,
        );
        assert!(matches!(
            parse_manifest(&bad),
            Err(Error::Unsupported("SegmentTemplate"))
        ));
    }

    #[test]
    fn accepts_loopback_proxy_base_urls() {
        let proxied = SHIM_MANIFEST
            .replacen(
                "https://rr1.googlevideo.com/videoplayback?expire=1&amp;id=137&amp;sig=a%3Db",
                "http://127.0.0.1:18080/track/1",
                1,
            )
            .replacen(
                "https://rr1.googlevideo.com/videoplayback?expire=1&amp;id=140&amp;sig=c%3Dd",
                "http://127.0.0.1:18080/track/2",
                1,
            );
        let m = parse_manifest(&proxied).expect("proxy manifest parses");
        assert_eq!(m.video.base_url, "http://127.0.0.1:18080/track/1");
        assert_eq!(m.audio.base_url, "http://127.0.0.1:18080/track/2");
    }

    #[test]
    fn rejects_missing_audio() {
        let bad = r#"<MPD type="static"><Period>
<AdaptationSet mimeType="video/mp4" width="640" height="360">
<SegmentBase indexRange="10-20"><Initialization range="0-9"/></SegmentBase>
<Representation id="1" bandwidth="1"><BaseURL>https://example.com/v.mp4</BaseURL></Representation>
</AdaptationSet></Period></MPD>"#;
        assert!(matches!(
            parse_manifest(bad),
            Err(Error::MissingTrack("audio"))
        ));
    }

    #[test]
    fn rejects_non_https_and_unknown_mime_and_encryption() {
        let http = SHIM_MANIFEST.replacen("https://rr1", "http://rr1", 1);
        assert!(matches!(parse_manifest(&http), Err(Error::NonHttpsBaseUrl)));
        let text = SHIM_MANIFEST.replacen("video/mp4", "text/vtt", 1);
        assert!(matches!(parse_manifest(&text), Err(Error::UnknownMime(_))));
        let cenc = SHIM_MANIFEST.replacen(
            "<Representation id=\"137\"",
            "<ContentProtection schemeUriId=\"urn:mpeg:dash:mpenc:classic:2011:cenc\"/><Representation id=\"137\"",
            1,
        );
        assert!(parse_manifest(&cenc).is_err());
    }
}
